CREATE TABLE IF NOT EXISTS workshop_checkouts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  registration_id INT UNSIGNED NOT NULL,
  workshop_id VARCHAR(40) NOT NULL,
  booking_id INT UNSIGNED NULL,
  public_token CHAR(64) NOT NULL,
  idempotency_key VARCHAR(64) NOT NULL,
  partner_reference VARCHAR(100) NOT NULL,
  request_json MEDIUMTEXT NOT NULL,
  provider_session_id VARCHAR(100) NULL,
  provider_status VARCHAR(24) NOT NULL DEFAULT 'created',
  checkout_url TEXT NULL,
  expires_at DATETIME NULL,
  amount INT UNSIGNED NULL,
  currency CHAR(3) NULL,
  raw_response MEDIUMTEXT NULL,
  last_checked_at DATETIME NULL,
  last_webhook_id VARCHAR(100) NULL,
  fulfillment_error VARCHAR(255) NULL,
  last_error VARCHAR(500) NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_wc_token (public_token),
  UNIQUE KEY uq_wc_key (idempotency_key),
  UNIQUE KEY uq_wc_reference (partner_reference),
  UNIQUE KEY uq_wc_session (provider_session_id),
  UNIQUE KEY uq_wc_booking (booking_id),
  KEY k_wc_person_workshop (registration_id,workshop_id,id),
  CONSTRAINT fk_wc_registration FOREIGN KEY (registration_id) REFERENCES registrations(id),
  CONSTRAINT fk_wc_workshop FOREIGN KEY (workshop_id) REFERENCES workshops(id),
  CONSTRAINT fk_wc_booking FOREIGN KEY (booking_id) REFERENCES workshop_bookings(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
